  function makeT(lang) {
    var dict = STRINGS[lang] || STRINGS.zh;
    return function (key, vars) {
      var s = dict[key];
      if (s === undefined) s = STRINGS.zh[key];
      if (s === undefined) s = key;
      if (vars) {
        Object.keys(vars).forEach(function (k) {
          s = s.split("{" + k + "}").join(vars[k]);
        });
      }
      return s;
    };
  }

